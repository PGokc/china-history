def upsert(items, item, key="id"):
    for index, old in enumerate(items):
        if old.get(key) == item[key]:
            items[index] = item
            return
    items.append(item)


def add_unique(items, *values):
    for value in values:
        if value not in items:
            items.append(value)


def section(section_id, title, text, sources, events, people):
    return {
        "id": section_id,
        "title": title,
        "text": text,
        "kind": "史实与解读",
        "sources": sources,
        "events": events,
        "people": people,
    }


def article(person, title, dek, sections):
    sources = []
    for item in sections:
        add_unique(sources, *item["sources"])
    return {"person": person, "title": title, "dek": dek, "sections": sections, "sources": sources}


def event(event_id, year, sort_year, title, category, body, impact, people, sources, kind):
    return {
        "id": event_id,
        "year": year,
        "sortYear": sort_year,
        "title": title,
        "category": category,
        "body": body,
        "impact": impact,
        "people": people,
        "sources": sources,
        "kind": kind,
    }


def add_association(data, source, target, role, inverse, period, note, sources):
    item = {
        "from": source,
        "to": target,
        "role": role,
        "inverse": inverse,
        "period": period,
        "note": note,
        "sources": sources,
    }
    for index, old in enumerate(data["associations"]):
        if old["from"] == source and old["to"] == target:
            data["associations"][index] = item
            return
    data["associations"].append(item)


