def main() -> None:
    data = json.loads(PATH.read_text())
    current_primary_ids = {source["id"] for source in PRIMARY_SOURCES}
    source_by_id = {
        source["id"]: source for source in data["sources"]
        if not source["id"].startswith("v126_liaoshi_") or source["id"] in current_primary_ids
    }
    source_by_id.update({source["id"]: source for source in PRIMARY_SOURCES})
    data["sources"] = list(source_by_id.values())

    articles = {article["person"]: article for article in data["articles"]}
    for person_id, reading in READINGS.items():
        article = articles[person_id]
        article["sections"] = [
            {
                "id": f"{person_id}-v126-{index}",
                "title": title,
                "text": text + EXTRAS[person_id][index - 1],
                "kind": "史实与解读",
                "events": [reading["events"][index - 1]],
                "people": [person_id, *reading["people"]],
                "sources": reading["sources"],
            }
            for index, (title, text) in enumerate(zip(reading["titles"], reading["texts"]), start=1)
        ]
        article["sources"] = reading["sources"]

    for event in data["events"]:
        if event["id"] in ENDINGS:
            event["body"] = ENDINGS[event["id"]]
            event["impact"] = ENDINGS[event["id"]]

    data["version"] = 100
    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print("rewrote nine Liao ruler readings and corrected generic reign endings")


if __name__ == "__main__":
    main()
